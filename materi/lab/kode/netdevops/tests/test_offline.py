ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))

import render  # noqa: E402
import sotlib  # noqa: E402
from tasks import normalize_iptables, parse_reload_test  # noqa: E402


@pytest.fixture(scope="module")
def intent():
    return sotlib.finalize(sotlib.load_seed(ROOT / "sot" / "seed.yml"))


@pytest.fixture(scope="module")
def rendered(intent, tmp_path_factory):
    out = tmp_path_factory.mktemp("render") / "build"
    policy = yaml.safe_load((ROOT / "policy" / "firewall.yml").read_text(encoding="utf-8"))
    render.render_tree(intent, policy, out)
    return out


def test_klasifikasi_interface(intent):
    kinds = {i["name"]: i["kind"] for i in intent["devices"]["r3"]["interfaces"]}
    assert kinds == {"lo": "loopback", "eth1": "p2p", "eth2": "p2p", "eth3": "lan", "eth4": "lan"}
    assert intent["devices"]["r3"]["router_id"] == "10.255.0.3"
    assert intent["devices"]["srv1"]["interfaces"][0]["gateway"] == "10.20.20.1"


def test_ip_ganda_ditolak():
    raw = sotlib.load_seed(ROOT / "sot" / "seed.yml")
    raw["devices"]["r4"]["interfaces"][1]["ip"] = "10.0.0.0/31"  # sama dengan r1:eth1
    with pytest.raises(sotlib.SoTError, match="dipakai ganda"):
        sotlib.finalize(raw)


def test_ip_di_luar_ipam_ditolak():
    raw = sotlib.load_seed(ROOT / "sot" / "seed.yml")
    raw["devices"]["h1"]["interfaces"][0]["ip"] = "192.168.1.10/24"
    with pytest.raises(sotlib.SoTError, match="tidak berada di prefix"):
        sotlib.finalize(raw)


def test_frr_diawali_frr_version(rendered):
    for f in (rendered / "configs").glob("*.frr.conf"):
        assert f.read_text().splitlines()[0].startswith("frr version"), f.name
        assert "\nexit\n" not in f.read_text(), "Batfish tidak mengenal 'exit'"


def test_snapshot_batfish_lengkap(rendered):
    cfg = (rendered / "batfish" / "configs" / "r1.cfg").read_text().splitlines()
    assert cfg[0] == "r1"
    assert "# This file describes the network interfaces" in cfg
    assert "# ports.conf --" in cfg
    hosts = sorted(p.stem for p in (rendered / "batfish" / "hosts").glob("*.json"))
    assert hosts == ["h1", "noc1", "srv1"]


def test_firewall_tanpa_opsi_yang_tidak_dimodelkan(rendered):
    text = (rendered / "configs" / "srv1.iptables").read_text()
    for bad in (" -i ", " -o ", "multiport", "conntrack", "--state"):
        assert bad not in text
    assert ":INPUT DROP [0:0]" in text
    assert "-A INPUT -s 10.99.0.0/24 -p tcp --dport 22 -j ACCEPT" in text


def test_render_deterministik(intent, tmp_path):
    policy = yaml.safe_load((ROOT / "policy" / "firewall.yml").read_text(encoding="utf-8"))
    a, b = tmp_path / "a", tmp_path / "b"
    render.render_tree(intent, policy, a)
    render.render_tree(intent, policy, b)
    assert render.tree_files(a) == render.tree_files(b)


def test_build_di_repo_sesuai_seed(rendered):
    """build/ yang di-commit di repositori contoh ini dirender dari seed."""
    committed = ROOT / "build"
    if not (committed / "intent.json").exists():
        pytest.skip("build/ belum dirender")
    assert render.tree_files(committed) == render.tree_files(rendered)


def test_parse_frr_reload_test():
    sample = """2026-10-13 10:00:00,123  INFO: Called via "Namespace(...)"

Lines To Delete
===============
interface eth2
 no ip ospf cost 100

Lines To Add
============
interface eth2
 ip ospf cost 10
"""
    diff = parse_reload_test(sample)
    assert diff.splitlines() == [
        "- interface eth2",
        "-  no ip ospf cost 100",
        "+ interface eth2",
        "+  ip ospf cost 10",
    ]
    assert parse_reload_test("") == ""


def test_normalisasi_iptables_save():
    running = """# Generated by iptables-save v1.8.11 (nf_tables) on Mon Oct 13 10:00:00 2026
*filter
:INPUT DROP [12:3456]
:FORWARD ACCEPT [0:0]
:OUTPUT ACCEPT [99:1234]
-A INPUT -p icmp -j ACCEPT
-A INPUT -s 10.99.0.0/24 -p tcp -m tcp --dport 22 -j ACCEPT
COMMIT
# Completed on Mon Oct 13 10:00:00 2026
"""
    candidate = """# Dihasilkan oleh scripts/render.py
*filter
:INPUT DROP [0:0]
:FORWARD ACCEPT [0:0]
:OUTPUT ACCEPT [0:0]
-A INPUT -p icmp -j ACCEPT
-A INPUT -s 10.99.0.0/24 -p tcp --dport 22 -j ACCEPT
COMMIT
"""
    assert normalize_iptables(running) == normalize_iptables(candidate)
